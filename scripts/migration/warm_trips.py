# -*- coding: utf-8 -*-
"""warm_trips.py — Pre-materialize trip sessions + seat inventory for the
next N days, as bulk SQL applied to the production DB.

Why: the app materializes trips on demand at search time (one transaction
per schedule). Routes with thousands of schedules (Hà Nội → Hải Phòng,
Huế → Đà Nẵng, …) exceed even a raised request timeout on their first
search per date. Pre-creating the rows in one bulk import makes every
search in the window instant; the app's on-demand path then finds the
trips already present and skips.

The rows this writes are exactly what the app itself would insert
(`ensure_trips_for_schedules_on_date`): a `trip_session` per
(schedule, date) plus a `seat_inventory` row per seat of the schedule's
bus layout, priced at `schedule.base_price_adult`.

Run AFTER the full data phase. Safe order:
  stop backend → backup DB → apply SQL → chown sidecars → start backend.

Usage:
  python3 warm_trips.py --days 7 --out warm_trips.sql
"""
from __future__ import annotations

import argparse
import json
import subprocess
import uuid
from datetime import date, timedelta
from pathlib import Path

HERE = Path(__file__).resolve().parent
DB = "/var/lib/docker/volumes/datxevui_vexevn-data/_data/app.db"


def uuid_blob(u) -> str:
    h = str(u).replace("-", "").lower()
    return f"X'{h}'"


def ssh_json(query: str):
    q = query.replace("'", "'\"'\"'")
    cmd = [__import__("sys").executable, str(HERE / "ssh_run.py"),
           f"printf '.mode json\\n{q}\\n.quit\\n' | "
           f"/opt/migration/rustqlite-cli {DB}"]
    try:
        out = subprocess.run(cmd, capture_output=True, text=True, timeout=280)
    except subprocess.TimeoutExpired as e:
        raise RuntimeError(f"ssh query timed out: {query[:120]}") from e
    txt = out.stdout
    start, end = txt.find("["), txt.rfind("]")
    if start == -1 or end == -1:
        raise RuntimeError(f"no JSON from CLI: {txt[:400]} | stderr: "
                           f"{out.stderr[:200]}")
    return json.loads(txt[start:end + 1])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--days", type=int, default=7)
    ap.add_argument("--start", default=None, help="YYYY-MM-DD (default today)")
    ap.add_argument("--out", default=str(HERE / "warm_trips.sql"))
    args = ap.parse_args()

    plan = json.loads((HERE / "migration_plan.json").read_text(encoding="utf-8"))
    state = json.loads((HERE / "migration_state.json").read_text(encoding="utf-8"))

    # seat ids per layout, straight from the production DB
    seat_rows = ssh_json(
        "SELECT hex(id) AS seat, hex(bus_layout_id) AS lay FROM seat;")
    seats_by_layout = {}
    for r in seat_rows:
        seats_by_layout.setdefault(r["lay"].lower(), []).append(r["seat"].lower())
    print(f"[warm] {len(seat_rows)} seats across "
          f"{len(seats_by_layout)} layouts on the server")

    sched_api = state.get("schedules", {})
    layout_by_id = {l["id"].replace("-", "").lower(): l
                    for l in plan["layouts"]}
    scheds = []
    for s in plan["schedules"]:
        api_id = sched_api.get(s["seed_id"])
        lay_hex = (s.get("layout_id") or "").replace("-", "").lower()
        if not api_id or lay_hex not in seats_by_layout:
            continue
        scheds.append({"api": api_id.replace("-", "").lower(),
                       "lay": lay_hex,
                       "price": s["base_price_adult"]})
    print(f"[warm] {len(scheds)} schedules with a seat map on the server")

    start = date.fromisoformat(args.start) if args.start else date.today()
    dates = [(start + timedelta(days=i)).isoformat() for i in range(args.days)]
    print(f"[warm] window: {dates[0]} .. {dates[-1]}")

    # existing (schedule, date) trips in the window on the server
    rows = ssh_json(
        "SELECT hex(schedule_id) AS sched, departure_date AS d "
        f"FROM trip_session WHERE departure_date BETWEEN "
        f"'{dates[0]}' AND '{dates[-1]}';")
    have = {(r["sched"].lower(), r["d"]) for r in rows}
    print(f"[warm] {len(have)} trips already exist in window")

    now = plan["generated_at"]
    lines = [
        "-- warm_trips.sql — generated by warm_trips.py",
        f"-- window: {dates[0]} .. {dates[-1]}",
        f"-- generated_at: {now}",
        "BEGIN;",
    ]
    n_trips = n_seats = 0
    for s in scheds:
        seat_ids = seats_by_layout[s["lay"]]
        n = len(seat_ids)
        for d in dates:
            if (s["api"], d) in have:
                continue
            trip_hex = uuid.uuid4().hex
            lines.append(
                "INSERT INTO trip_session (id, schedule_id, departure_date, "
                "actual_departure_at, driver_name, driver_phone, status, "
                "total_seats, available_seats, created_at, updated_at) VALUES ("
                f"X'{trip_hex}', X'{s['api']}', '{d}', NULL, NULL, NULL, "
                f"'scheduled', {n}, {n}, '{now}', '{now}');")
            lines.append(
                "INSERT INTO seat_inventory (id, trip_session_id, seat_id, "
                "status, base_price, final_price, currency, held_until, "
                "held_by_booking_id, created_at, updated_at) VALUES " +
                ",".join(
                    f"(X'{uuid.uuid4().hex}', X'{trip_hex}', X'{sid}', "
                    f"'available', {s['price']}, {s['price']}, 'VND', "
                    f"NULL, NULL, '{now}', '{now}')"
                    for sid in seat_ids) + ";")
            n_trips += 1
            n_seats += n
    lines.append("COMMIT;")
    Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print(f"[warm] wrote {args.out}: {n_trips} trips, {n_seats} seat rows "
          f"({sum(1 for l in lines if l.startswith('INSERT'))} statements)")


if __name__ == "__main__":
    main()
