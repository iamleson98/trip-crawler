def restore_province(v):
    return PROVINCE_VI.get((v or "").strip()) if v else None


def restore_ward(v):
    if not v:
        return None
    v = v.strip()
    return WARD_VI.get(v, v)


def restore_district(v):
    if not v:
        return None
    v = v.strip()
    return DISTRICT_VI.get(v, v)


def one_space(s):
    """Collapse all whitespace runs to a single space, trim ends."""
    return " ".join((s or "").split())
